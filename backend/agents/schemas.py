class ListRegionsInput(BaseModel):
    """Input for listing available geographic datasets."""
    pass


class RegionItem(BaseModel):
    id: str
    label: str
    area: str


class ListRegionsOutput(BaseModel):
    regions: list[RegionItem]


class GetMonthlyActivityInput(BaseModel):
    """Input for querying monthly hotspot activity."""
    region: str = Field(default="sri-lanka", description="Region alias, e.g. 'sri-lanka' or 'demo'")
    start_month: str | None = Field(default=None, description="Start month formatted 'YYYY-MM'")
    end_month: str | None = Field(default=None, description="End month formatted 'YYYY-MM'")
    sensor_basis: str = Field(default="harmonized", description="Primary sensor basis: 'harmonized', 'MODIS_SP', 'VIIRS_SNPP_SP', 'VIIRS_NOAA20_SP'")


class MonthlyRecord(BaseModel):
    month: str
    MODIS_SP: float | None = None
    VIIRS_SNPP_SP: float | None = None
    VIIRS_NOAA20_SP: float | None = None
    harmonized: float | None = None
    origin: str


class GetMonthlyActivityOutput(BaseModel):
    region: str
    records: list[MonthlyRecord]
    total_months: int


class GetCoverageStatusInput(BaseModel):
    """Input for checking daily partition presence across a period."""
    region: str = Field(default="sri-lanka", description="Region alias")
    product: str = Field(default="VIIRS_SNPP_SP", description="Product code: 'MODIS_SP', 'VIIRS_SNPP_SP', 'VIIRS_NOAA20_SP'")
    start_date: str = Field(description="Start UTC date 'YYYY-MM-DD'")
    end_date: str = Field(description="End UTC date 'YYYY-MM-DD'")


class CoverageStatusOutput(BaseModel):
    region: str
    product: str
    start_date: str
    end_date: str
    expected_days: int
    present_days: int
    missing_days: int
    is_complete: bool
    status: str


class CompareSensorsInput(BaseModel):
    """Input for comparing satellite sensors across matched paired months."""
    region: str = Field(default="sri-lanka", description="Region alias")
    start_month: str | None = Field(default=None, description="Start month 'YYYY-MM'")
    end_month: str | None = Field(default=None, description="End month 'YYYY-MM'")
    sensors: list[str] = Field(default_factory=lambda: ["MODIS_SP", "VIIRS_SNPP_SP"], description="Sensors to compare")


class SensorComparisonOutput(BaseModel):
    region: str
    matched_months: int
    summary: dict[str, Any]
    holdout_mae: dict[str, Any] | None = None


class GetSeasonalDepartureInput(BaseModel):
    """Input for computing historical seasonal departure (anomaly)."""
    region: str = Field(default="sri-lanka", description="Region alias")
    year: int = Field(description="Target year (e.g. 2023)")
    month: int = Field(ge=1, le=12, description="Target calendar month (1-12)")
    sensor_basis: str = Field(default="harmonized", description="Sensor column: 'harmonized', 'MODIS_SP', 'VIIRS_SNPP_SP'")


class SeasonalDepartureOutput(BaseModel):
    region: str
    target_month: str
    value: float | None
    historical_median: float | None
    departure_detections: float | None
    departure_percent: float | None
    prior_years_count: int
    status: str


class GetCalibrationSummaryInput(BaseModel):
    """Input for retrieving regional calibration factor and holdout metrics."""
    region: str = Field(default="sri-lanka", description="Region alias")


class CalibrationSummaryOutput(BaseModel):
    region: str
    calibration_factor: float | None
    paired_months: int
    training_months: int
    holdout_months: int
    raw_mae: float | None
    adjusted_mae: float | None
    absolute_error_p90: float | None


class GetHoldoutMetricsInput(BaseModel):
    """Input for retrieving holdout validation evaluation tables."""
    region: str = Field(default="sri-lanka", description="Region alias")


class HoldoutMetricsOutput(BaseModel):
    region: str
    metrics: list[dict[str, Any]]


class GetHotspotDetectionsInput(BaseModel):
    """Input for reading daily active fire detections with pagination."""
    region: str = Field(default="sri-lanka", description="Region alias")
    day: str = Field(description="UTC day 'YYYY-MM-DD'")
    product: str = Field(default="MODIS_SP", description="Sensor product code")
    limit: int = Field(default=1000, ge=1, le=10000, description="Max detections to return")
    offset: int = Field(default=0, ge=0, description="Pagination offset")
    bbox: str | None = Field(default=None, description="Optional west,south,east,north bounding box")


class HotspotItem(BaseModel):
    latitude: float
    longitude: float
    acq_date: str
    satellite: str
    confidence: str | float | None
    frp: float | None
    acquired_utc: str | None


class GetHotspotDetectionsOutput(BaseModel):
    region: str
    day: str
    product: str
    total: int
    offset: int
    limit: int
    detections: list[HotspotItem]


class GetMapLayersActionInput(BaseModel):
    """Input for validating map layer bounds and generating UI action."""
    region: str = Field(default="sri-lanka", description="Region alias")
    start_date: str = Field(description="Start UTC date 'YYYY-MM-DD'")
    end_date: str = Field(description="End UTC date 'YYYY-MM-DD'")
    bbox: str | None = Field(default=None, description="Optional bounding box 'west,south,east,north'")
    polygon: str | None = Field(default=None, description="Optional polygon 'lon,lat;lon,lat;...'")
    enabled_layers: list[str] = Field(default_factory=lambda: ["MODIS_SP", "VIIRS_SNPP_SP", "harmonized"])


class MapLayersActionOutput(BaseModel):
    region: str
    start_date: str
    end_date: str
    expected_days: int
    layers_summary: dict[str, Any]
    ui_action: UIAction


class GenerateExportReferenceInput(BaseModel):
    """Input for generating a secure CSV download reference."""
    region: str = Field(default="sri-lanka", description="Region alias")
    year: int | None = Field(default=None, description="Optional year filter")
    export_type: Literal["monthly", "detections"] = Field(default="monthly", description="Type of export")
    month: str | None = Field(default=None, description="Month 'YYYY-MM' if export_type is 'detections'")
    source: str | None = Field(default=None, description="Sensor product code if export_type is 'detections'")


class GenerateExportReferenceOutput(BaseModel):
    download: DownloadItem
    metadata: dict[str, Any]
