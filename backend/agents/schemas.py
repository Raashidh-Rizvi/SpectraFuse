"""Typed Pydantic contracts and schemas for the SpectraFuse Agentic AI system."""

from typing import Any, Literal
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Core Chat Communication Contracts
# ---------------------------------------------------------------------------

class ChatContext(BaseModel):
    """Client conversation context forwarded from dashboard state."""
    current_year: str | None = Field(default=None, description="Currently selected year (e.g. '2022' or 'all')")
    sensor_basis: str = Field(default="harmonized", description="Selected sensor basis (e.g. 'harmonized', 'MODIS_SP')")
    last_bounds: str | None = Field(default=None, description="Last selected or viewed bounding box (west,south,east,north)")


class Message(BaseModel):
    """Individual chat turn for session history."""
    role: Literal["user", "assistant", "system"]
    content: str = Field(min_length=1, max_length=4000)


class ChatRequest(BaseModel):
    """Inbound request from the client to the agentic assistant."""
    message: str = Field(default="", max_length=4000, description="Natural-language question from the user")
    question: str | None = Field(default=None, description="Legacy field alias for message")
    session_id: str | None = Field(default=None, max_length=128, description="Unique session ID for memory continuity")
    region: str = Field(default="sri-lanka", max_length=100, description="Target region alias (e.g. 'sri-lanka' or 'demo')")
    context: ChatContext | None = Field(default=None, description="Optional active dashboard filter context")
    history: list[Message] = Field(default_factory=list, max_length=10, description="Recent conversation turns")

    def model_post_init(self, __context: Any) -> None:
        if not self.message and self.question:
            self.message = self.question


class EvidenceItem(BaseModel):
    """Structured machine-readable evidence attached to each agent response."""
    source: str = Field(description="Data origin (e.g. 'monthly.parquet', 'daily_partition')")
    product: str | None = Field(default=None, description="Sensor product code (e.g. 'VIIRS_SNPP_SP', 'MODIS_SP')")
    metric: str = Field(description="Name of metric (e.g. 'hotspot_detections', 'departure_percent')")
    value: Any = Field(description="Exact value retrieved from the dataset")
    status: str = Field(description="'observed', 'estimated', 'complete', 'partial', or 'unavailable'")
    coverage: str = Field(default="complete", description="Partition coverage completeness description")
    calibration_applied: bool = Field(default=False, description="Whether regional scaling multiplier was applied")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Additional context or provenance fields")


class CalculationStep(BaseModel):
    """Step-by-step arithmetic breakdown executed by code, never by the LLM."""
    step: str = Field(description="Descriptive name of the computation step")
    formula: str = Field(description="Mathematical expression evaluated")
    result: Any = Field(description="Evaluated numerical result")


class UIAction(BaseModel):
    """Structured client-side action instructing the dashboard to update view state."""
    type: Literal["show_on_map", "apply_filters", "open_monthly_trend", "highlight_calendar_cell"]
    payload: dict[str, Any] = Field(description="Action payload containing target region, dates, layers, or bbox")


class DownloadItem(BaseModel):
    """Download reference generated by the backend for exact query data."""
    label: str = Field(description="User-friendly download description")
    url: str = Field(description="Secure download endpoint URL")
    format: str = Field(default="csv", description="File format, typically 'csv'")


class ChatResponse(BaseModel):
    """Complete structured response emitted by the agentic orchestrator."""
    request_id: str = Field(description="Unique tracking ID for observability and audit logging")
    session_id: str = Field(description="Active session ID")
    intent: str = Field(description="Classified user intent")
    answer: str = Field(description="Human-readable plain text response with direct answer first")
    region: str = Field(description="Region analyzed")
    period: dict[str, str] | None = Field(default=None, description="Start and end dates or month analyzed")
    evidence: list[EvidenceItem] = Field(default_factory=list, description="Machine-readable evidence trail")
    calculations: list[CalculationStep] = Field(default_factory=list, description="Step-by-step calculations")
    limitations: list[str] = Field(default_factory=list, description="Scientific disclaimers and limitations")
    ui_actions: list[UIAction] = Field(default_factory=list, description="Client actions to execute on the dashboard")
    downloads: list[DownloadItem] = Field(default_factory=list, description="Direct download links")


